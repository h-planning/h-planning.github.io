-- ---------- Jours fériés français et jours ouvrables ----------
create or replace function public.easter(y int) returns date
language plpgsql immutable as $$
declare a int; b int; c int; d int; e int; f int; g int; h int; i int; k int; l int; m int; mo int; dy int;
begin
  a := y % 19; b := y / 100; c := y % 100; d := b / 4; e := b % 4; f := (b + 8) / 25; g := (b - f + 1) / 3;
  h := (19*a + b - d - g + 15) % 30; i := c / 4; k := c % 4; l := (32 + 2*e + 2*i - h - k) % 7;
  m := (a + 11*h + 22*l) / 451; mo := (h + l - 7*m + 114) / 31; dy := ((h + l - 7*m + 114) % 31) + 1;
  return make_date(y, mo, dy);
end $$;

create or replace function public.is_holiday(d date) returns boolean
language plpgsql immutable as $$
declare e date := public.easter(extract(year from d)::int);
begin
  return to_char(d, 'MM-DD') in ('01-01','05-01','05-08','07-14','08-15','11-01','11-11','12-25')
      or d in (e + 1, e + 39, e + 50);
end $$;

create or replace function public.is_ouvrable(d date) returns boolean
language sql immutable as $$ select extract(isodow from d) <> 7 and not public.is_holiday(d) $$;

create or replace function public.count_ouvrables(s date, e date) returns int
language sql immutable as $$
  select count(*)::int from generate_series(s, e, interval '1 day') g(d) where public.is_ouvrable(g.d::date)
$$;

