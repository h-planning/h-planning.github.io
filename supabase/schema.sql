-- ---------- Demandes ----------
-- type : cp | ferie (jour férié) | recup (jour récupéré) | anciennete | ot_day (récup heures supp)
-- circuit : pending_manager → (cp) pending_admin → approved | refused | cancelled
create table public.requests (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null default auth.uid() references public.profiles on delete cascade on update cascade,
  service_id smallint not null references public.services,
  type text not null check (type in ('cp','ferie','recup','anciennete','ot_day')),
  start_date date not null,
  end_date date not null,
  days numeric(5,1) not null default 0,
  comment text,
  status text not null default 'pending_manager'
    check (status in ('pending_manager','pending_admin','approved','refused','cancelled')),
  created_by uuid default auth.uid(),
  manager_id uuid references public.profiles on update cascade,
  manager_at timestamptz,
  admin_id uuid references public.profiles on update cascade,
  admin_at timestamptz,
  refusal_reason text,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);
create index on public.requests (service_id, status);

create or replace function public.type_label(t text) returns text language sql immutable as
$$ select case t when 'cp' then 'Congés payés' when 'recup' then 'Jour récupéré' when 'ferie' then 'Jour férié'
                 when 'rendre' then 'Jour à rendre' when 'anciennete' then 'Jour d''ancienneté'
                 when 'ot_day' then 'Récup heures supp' when 'maladie' then 'Arrêt maladie' when 'at' then 'Accident du travail'
                 when 'css' then 'Congé sans solde' when 'absence' then 'Absence' when 'formation' then 'Formation'
                 when 'repos' then 'Repos' else t end $$;

create or replace function public.requests_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare me profiles; p profiles; pending numeric; dl smallint; otb int;
begin
  select * into me from profiles where id = auth.uid();
  if me.id is null or me.role = 'pending' or not me.active then raise exception 'Compte non activé.'; end if;
  new.employee_id := coalesce(new.employee_id, me.id);
  select * into p from profiles where id = new.employee_id;
  if p.id is null then raise exception 'Salarié introuvable.'; end if;
  new.service_id := coalesce(p.service_id, (select min(service_id) from profile_services where profile_id = p.id));
  if new.service_id is null then raise exception 'Ce salarié n''a pas de service.'; end if;
  new.created_by := me.id;
  new.status := 'pending_manager';
  new.manager_id := null; new.admin_id := null; new.manager_at := null; new.admin_at := null;

  -- les demandes sont saisies par l'encadrement (droit « requests ») pour un salarié ; jamais par le salarié lui-même.
  -- La demande d'un manager ou d'un assistant est saisie par l'administrateur.
  if p.id = me.id and not public.is_admin() then
    raise exception 'Les demandes sont saisies par votre manager.';
  elsif not exists (select 1 from profile_services ps where ps.profile_id = p.id and public.can('requests', ps.service_id)) then
    raise exception 'Vous ne pouvez saisir des demandes que pour les salariés que vous gérez.';
  elsif p.role in ('manager','assistant','admin') and not public.is_admin() then
    raise exception 'La demande d''un membre de l''encadrement est saisie par l''administrateur.';
  end if;

  -- CP en jours ouvrables (2,5 j par mois) : si le lendemain de la fin est le 1er jour de repos du salarié, il est décompté aussi
  if new.type = 'cp' and extract(isodow from new.end_date + 1)::smallint = public.cp_rest_day(p.id) and public.is_ouvrable(new.end_date + 1) then
    new.end_date := new.end_date + 1;
  end if;
  new.days := case when new.type in ('cp') then public.count_ouvrables(new.start_date, new.end_date)
                   else (new.end_date - new.start_date + 1) end;
  if new.days = 0 then raise exception 'La période choisie ne contient aucun jour ouvrable.'; end if;
  select coalesce(sum(days), 0) into pending from requests
   where employee_id = p.id and type = new.type and status in ('pending_manager','pending_admin');
  if new.type = 'cp' and new.days + pending > p.cp_balance then
    raise exception 'Solde de congés insuffisant (% j disponibles, % j déjà demandés).', trim_scale(p.cp_balance), trim_scale(pending);
  elsif new.type = 'ferie' and new.days + pending > p.ferie_balance then
    raise exception 'Solde de jours fériés insuffisant (% j disponibles).', trim_scale(p.ferie_balance);
  elsif new.type = 'recup' and new.days + pending > p.recup_days then
    raise exception 'Pas assez de jours à récupérer (% j dus).', trim_scale(p.recup_days);
  elsif new.type = 'anciennete' and new.days + pending > p.seniority_balance then
    raise exception 'Solde de jours d''ancienneté insuffisant (% j).', trim_scale(p.seniority_balance);
  elsif new.type = 'ot_day' then
    otb := public.ot_balance(p.id);
    if (new.days + pending) * (select ot_day_minutes from settings where id = p.company_id) > otb then
      raise exception 'Solde d''heures supp insuffisant (% disponibles).', to_char(make_interval(mins => greatest(otb, 0)), 'HH24"h"MI');
    end if;
  end if;
  return new;
end $$;
create trigger requests_before_insert before insert on public.requests
for each row execute function public.requests_before_insert();

create or replace function public.requests_after_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare who text;
begin
  if not public.notify_on('request') then return null; end if;
  select coalesce(nullif(full_name, ''), email) into who from profiles where id = new.employee_id;
  insert into notifications (user_id, title, body)
  select p.id, 'Nouvelle demande', who || ' : ' || public.type_label(new.type) || ' du ' || to_char(new.start_date, 'DD/MM')
         || ' au ' || to_char(new.end_date, 'DD/MM') || ' (' || trim_scale(new.days) || ' j).'
  from profiles p where p.active and p.has_account and p.role in ('manager','assistant') and p.id <> new.employee_id
    and public.works_in(p.id, new.service_id)
    and coalesce(((select rights from settings where id = public.svc_company(new.service_id)) -> p.role ->> 'requests')::boolean, false);
  return null;
end $$;
create trigger requests_after_insert after insert on public.requests
for each row execute function public.requests_after_insert();

-- Applique une demande validée : remplace le planning de la période, les compteurs suivent automatiquement
create or replace function public.apply_request(r requests) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform set_config('hpg.silent', '1', true);
  delete from shifts where employee_id = r.employee_id and day between r.start_date and r.end_date;
  insert into shifts (employee_id, service_id, day, kind, request_id, label)
  select r.employee_id, r.service_id, g.d::date, r.type, r.id, public.type_label(r.type)
  from generate_series(r.start_date, r.end_date, interval '1 day') g(d);
  perform set_config('hpg.silent', '0', true);
end $$;
revoke execute on function public.apply_request(requests) from public, anon, authenticated;

create or replace function public.decide_request(p_id uuid, p_approve boolean, p_reason text default null)
returns requests language plpgsql security definer set search_path = public as $$
declare r requests; lbl text;
begin
  select * into r from requests where id = p_id for update;
  if r.id is null or not public.in_my_company(r.service_id) then raise exception 'Demande introuvable.'; end if;
  if not p_approve and coalesce(trim(p_reason), '') = '' then raise exception 'Indiquez le motif du refus.'; end if;
  lbl := public.type_label(r.type) || ' du ' || to_char(r.start_date, 'DD/MM') || ' au ' || to_char(r.end_date, 'DD/MM');

  if r.status = 'pending_manager' then
    if not public.can('requests', r.service_id) then raise exception 'Vous ne gérez pas les demandes de ce service.'; end if;
    if r.employee_id = auth.uid() and not public.is_admin() then raise exception 'Vous ne pouvez pas valider votre propre demande.'; end if;
    -- la demande d'un manager ou d'un assistant est validée par l'administrateur
    if not public.is_admin() and (select role from profiles where id = r.employee_id) in ('manager','assistant','admin') then
      raise exception 'Les demandes de l''encadrement sont validées par l''administrateur.';
    end if;
    update requests set manager_id = auth.uid(), manager_at = now() where id = r.id;
    if not p_approve then
      update requests set status = 'refused', refusal_reason = p_reason where id = r.id;
      if public.notify_on('decision') then perform public.notify(r.employee_id, 'Demande refusée', lbl || ' — ' || p_reason); end if;
    elsif r.type = 'cp' and not public.is_admin() then
      update requests set status = 'pending_admin' where id = r.id;
      if public.notify_on('decision') then
        perform public.notify(r.employee_id, 'Demande validée par votre manager', lbl || ' : en attente de la validation finale.');
        insert into notifications (user_id, title, body)
        select id, 'Congés à valider', lbl || ' — validé par le manager.' from profiles where role = 'admin' and active and has_account and company_id = public.svc_company(r.service_id);
      end if;
    else
      update requests set status = 'approved', admin_id = case when r.type = 'cp' then auth.uid() end,
                          admin_at = case when r.type = 'cp' then now() end where id = r.id;
      select * into r from requests where id = p_id;
      perform public.apply_request(r);
      if public.notify_on('decision') then perform public.notify(r.employee_id, 'Demande acceptée', lbl); end if;
    end if;

  elsif r.status = 'pending_admin' then
    if not public.is_admin() then raise exception 'Seul l''administrateur peut donner la validation finale.'; end if;
    update requests set admin_id = auth.uid(), admin_at = now() where id = r.id;
    if p_approve then
      update requests set status = 'approved' where id = r.id;
      select * into r from requests where id = p_id;
      perform public.apply_request(r);
      if public.notify_on('decision') then perform public.notify(r.employee_id, 'Congés acceptés', lbl); end if;
    else
      update requests set status = 'refused', refusal_reason = p_reason where id = r.id;
      if public.notify_on('decision') then perform public.notify(r.employee_id, 'Congés refusés', lbl || ' — ' || p_reason); end if;
    end if;
  else
    raise exception 'Cette demande a déjà été traitée.';
  end if;
  select * into r from requests where id = p_id;
  return r;
end $$;

create or replace function public.cancel_request(p_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare r requests;
begin
  if not public.mfa_ok() then raise exception 'Connexion non vérifiée.'; end if;
  select * into r from requests where id = p_id;
  if r.id is null or not (r.employee_id = auth.uid() or r.created_by = auth.uid() or public.can('requests', r.service_id)) then
    raise exception 'Demande introuvable.';
  end if;
  update requests set status = 'cancelled' where id = p_id and status in ('pending_manager','pending_admin');
  if not found then raise exception 'Seule une demande en attente peut être annulée.'; end if;
end $$;

-- ---------- Gestion des fiches salariés ----------
-- Développeur / administrateur : tout (le compte développeur n'est modifiable que par lui-même).
-- Manager / assistant avec le droit « team » : salariés de ses services, sans rôles ni soldes.
create or replace function public.update_profile(p_id uuid, p jsonb) returns profiles
language plpgsql security definer set search_path = public as $$
declare t profiles; me_role text := public.my_role(); svcs smallint[]; s smallint; newsvc smallint;
begin
  select * into t from profiles where id = p_id for update;
  if t.id is null then raise exception 'Fiche introuvable.'; end if;
  if t.role = 'developer' and p_id <> auth.uid() then raise exception 'Fiche introuvable.'; end if;
  if p_id <> auth.uid() and t.company_id is distinct from public.my_company() and not (public.is_dev() and t.company_id is null) then
    raise exception 'Fiche introuvable.';
  end if;
  if p ? 'role' and p->>'role' = 'developer' and t.role <> 'developer' then raise exception 'Ce rôle ne peut pas être attribué.'; end if;
  if t.role = 'developer' and p ? 'role' and p->>'role' <> 'developer' then raise exception 'Le compte développeur garde son rôle.'; end if;
  if t.role = 'developer' and p ? 'active' and not (p->>'active')::boolean then raise exception 'Le compte développeur ne peut pas être désactivé.'; end if;
  if p ? 'hire_date' and nullif(p->>'hire_date', '') is null and t.role not in ('developer') then raise exception 'La date d''entrée est obligatoire.'; end if;
  if p ? 'services' then select array_agg(x::smallint) into svcs from jsonb_array_elements_text(p->'services') x; end if;
  newsvc := case when p ? 'service_id' then nullif(p->>'service_id', '')::smallint
                 when svcs is not null and not (t.service_id = any(svcs)) then svcs[1] else t.service_id end;

  if public.is_admin() then
    if svcs is not null then foreach s in array svcs loop
      if not public.in_my_company(s) then raise exception 'Service d''une autre entreprise.'; end if;
    end loop; end if;
    if newsvc is not null and not public.in_my_company(newsvc) then raise exception 'Service d''une autre entreprise.'; end if;
    if t.company_id is null and t.id <> auth.uid() then update profiles set company_id = public.my_company() where id = t.id; end if;
  elsif me_role in ('manager','assistant') then
    if not exists (select 1 from profile_services ps where ps.profile_id = t.id and public.can('team', ps.service_id)) and t.role <> 'pending' then
      raise exception 'Vous ne pouvez modifier que les salariés de vos services.';
    end if;
    if t.role not in ('employee','pending') then raise exception 'Seul l''administrateur peut modifier cette fiche.'; end if;
    if (p ? 'role' and p->>'role' not in ('employee','pending'))
       or p ?| array['cp_balance','seniority_balance','recup_adjust_min'] then
      raise exception 'Seul l''administrateur peut changer les rôles ou les soldes.';
    end if;
    if svcs is not null then
      foreach s in array svcs loop
        if not public.can('team', s) then raise exception 'Vous ne gérez pas tous ces services.'; end if;
      end loop;
    end if;
    if newsvc is not null and not public.can('team', newsvc) then raise exception 'Vous ne gérez pas ce service.'; end if;
  else
    raise exception 'Accès refusé.';
  end if;

  update profiles set
    full_name      = coalesce(nullif(trim(p->>'full_name'), ''), full_name),
    email          = case when p ? 'email' and not has_account then nullif(lower(trim(p->>'email')), '') else email end,
    contract_type  = coalesce(p->>'contract_type', contract_type),
    role           = coalesce(p->>'role', role),
    service_id     = newsvc,
    location       = case when p ? 'location' then nullif(p->>'location', '') else location end,
    job_title      = case when p ? 'job_title' then nullif(p->>'job_title', '') else job_title end,
    weekly_rest    = case when p ? 'weekly_rest' then (select coalesce(array_agg(x::smallint), '{}') from jsonb_array_elements_text(p->'weekly_rest') x) else weekly_rest end,
    contract_hours = coalesce((p->>'contract_hours')::numeric, contract_hours),
    hire_date      = case when p ? 'hire_date' then (p->>'hire_date')::date else hire_date end,
    cp_balance     = coalesce((p->>'cp_balance')::numeric, cp_balance),
    seniority_balance = coalesce((p->>'seniority_balance')::numeric, seniority_balance),
    recup_adjust_min = coalesce((p->>'recup_adjust_min')::int, recup_adjust_min),
    active         = coalesce((p->>'active')::boolean, active)
  where id = p_id returning * into t;
  if svcs is not null then
    delete from profile_services where profile_id = t.id and service_id <> all(svcs) and service_id is distinct from t.service_id;
    insert into profile_services select t.id, x from unnest(svcs) x on conflict do nothing;
  end if;
  return t;
end $$;

-- Ajouter une fiche sans compte de connexion (extra, intérimaire…) ; avec compte : fonction « manage-user »
create or replace function public.add_staff(p jsonb) returns profiles
language plpgsql security definer set search_path = public as $$
declare t profiles; svc smallint; svcs smallint[]; s smallint; r text := coalesce(nullif(p->>'role', ''), 'employee');
begin
  select array_agg(x::smallint) into svcs from jsonb_array_elements_text(coalesce(p->'services', '[]')) x;
  svc := coalesce(nullif(p->>'service_id', '')::smallint, svcs[1]);
  if svc is null then raise exception 'Choisissez un service.'; end if;
  if r not in ('employee','assistant','manager','admin') then raise exception 'Rôle invalide.'; end if;
  if not public.in_my_company(svc) then raise exception 'Service d''une autre entreprise.'; end if;
  if svcs is not null then foreach s in array svcs loop
    if not public.in_my_company(s) then raise exception 'Service d''une autre entreprise.'; end if;
  end loop; end if;
  if not public.is_admin() then
    if not public.can('team', svc) or r <> 'employee' then raise exception 'Accès refusé.'; end if;
    if svcs is not null then foreach s in array svcs loop
      if not public.can('team', s) then raise exception 'Vous ne gérez pas tous ces services.'; end if;
    end loop; end if;
  end if;
  if coalesce(trim(p->>'full_name'), '') = '' then raise exception 'Indiquez le nom du salarié.'; end if;
  if nullif(p->>'hire_date', '') is null then raise exception 'La date d''entrée est obligatoire.'; end if;
  insert into profiles (company_id, email, has_account, full_name, role, service_id, location, job_title, weekly_rest, contract_type, contract_hours, hire_date)
  values (public.my_company(), nullif(lower(trim(p->>'email')), ''), false, trim(p->>'full_name'), r, svc, nullif(p->>'location', ''), nullif(p->>'job_title', ''),
          (select coalesce(array_agg(x::smallint), '{}') from jsonb_array_elements_text(coalesce(p->'weekly_rest', '[]')) x),
          coalesce(p->>'contract_type', 'extra'), coalesce((p->>'contract_hours')::numeric, 39), (p->>'hire_date')::date)
  returning * into t;
  if svcs is not null then insert into profile_services select t.id, x from unnest(svcs) x on conflict do nothing; end if;
  return t;
exception when unique_violation then
  raise exception 'Un salarié existe déjà avec cet e-mail.';
end $$;

-- ---------- Acquisition des congés payés ----------
-- Chaque année à la date de crédit (1er mai par défaut), chaque salarié des contrats concernés (CDI, CDD, alternant)
-- reçoit les jours acquis sur la période écoulée (1er mai N-1 → 30 avril N) : 2,5 jours par mois depuis sa date
-- d'entrée, au prorata, arrondis au jour supérieur, plafonnés (30 jours).
create or replace function public.cp_earned(hire date, ps date, pe date, rate numeric, cap numeric default 30) returns numeric
language plpgsql immutable as $$
declare s date := greatest(coalesce(hire, ps), ps); m int; d date; rem int;
begin
  if hire is null or s > pe then return 0; end if;
  m := (extract(year from age(pe + 1, s)) * 12 + extract(month from age(pe + 1, s)))::int;
  d := (s + make_interval(months => m))::date;
  rem := (pe + 1) - d;
  return least(cap, ceil(rate * (m + rem / 30.0) - 0.000001));
end $$;

create or replace function public.cp_last_credit_date(p_date date, p_company smallint default 1) returns date
language sql stable security definer set search_path = public as $$
  select case when make_date(extract(year from p_date)::int, cp_credit_month, cp_credit_day) <= p_date
              then make_date(extract(year from p_date)::int, cp_credit_month, cp_credit_day)
              else make_date(extract(year from p_date)::int - 1, cp_credit_month, cp_credit_day) end
  from settings where id = p_company
$$;

create table public.cp_accruals (
  company_id smallint not null default 1 references public.companies on delete cascade,
  period_end date not null,
  period_start date not null,
  employees integer not null,
  total_days numeric(7,1) not null,
  done_by uuid,
  done_at timestamptz not null default now(),
  primary key (company_id, period_end)
);

-- crédit des CP d'une entreprise (selon ses propres paramètres)
create or replace function public.accrue_cp_company(p_company smallint, p_date date) returns integer
language plpgsql security definer set search_path = public as $$
declare ref date := public.cp_last_credit_date(p_date, p_company); ps date; pe date; st settings; n integer; tot numeric;
begin
  pe := ref - 1; ps := (ref - interval '1 year')::date;
  if exists (select 1 from cp_accruals where company_id = p_company and period_end = pe) then
    raise exception 'Les congés de la période du % au % ont déjà été crédités.', to_char(ps, 'DD/MM/YYYY'), to_char(pe, 'DD/MM/YYYY');
  end if;
  select * into st from settings where id = p_company;
  select count(*), coalesce(sum(public.cp_earned(hire_date, ps, pe, st.cp_monthly_days, st.cp_cap)), 0) into n, tot from profiles
   where company_id = p_company and active and role in ('employee','assistant','manager','admin') and contract_type = any(st.cp_contracts) and hire_date is not null and hire_date <= pe;
  update profiles set cp_balance = cp_balance + public.cp_earned(hire_date, ps, pe, st.cp_monthly_days, st.cp_cap)
   where company_id = p_company and active and role in ('employee','assistant','manager','admin') and contract_type = any(st.cp_contracts) and hire_date is not null and hire_date <= pe;
  insert into cp_accruals (company_id, period_end, period_start, employees, total_days, done_by) values (p_company, pe, ps, n, tot, auth.uid());
  if coalesce((st.notify ->> 'credit')::boolean, true) then
    insert into notifications (user_id, title, body)
    select id, 'Congés payés crédités', 'Vos congés acquis du ' || to_char(ps, 'DD/MM/YYYY') || ' au ' || to_char(pe, 'DD/MM/YYYY') || ' ont été ajoutés à votre solde.'
    from profiles where company_id = p_company and active and has_account and role in ('employee','assistant','manager','admin') and contract_type = any(st.cp_contracts) and hire_date is not null and hire_date <= pe;
  end if;
  return n;
end $$;
revoke execute on function public.accrue_cp_company(smallint, date) from public, anon, authenticated;

-- administrateur : son entreprise ; tâche planifiée (pg_cron, chaque nuit) : chaque entreprise le jour de sa date de crédit
create or replace function public.accrue_cp(p_date date default current_date) returns integer
language plpgsql security definer set search_path = public as $$
declare c record; n integer := 0;
begin
  if auth.uid() is not null then
    if not public.is_admin() then raise exception 'Réservé à l''administrateur.'; end if;
    return public.accrue_cp_company(public.my_company(), p_date);
  end if;
  for c in select co.id from companies co join settings st on st.id = co.id where co.active loop
    if public.cp_last_credit_date(p_date, c.id) = p_date
       and not exists (select 1 from cp_accruals where company_id = c.id and period_end = p_date - 1) then
      n := n + public.accrue_cp_company(c.id, p_date);
    end if;
  end loop;
  return n;
end $$;

-- ---------- Jours d'ancienneté ----------
-- +seniority_days jour(s) à chaque tranche de seniority_years ans depuis la date d'entrée (5, 10, 15 ans…),
-- crédités à la date anniversaire (fonction appelée chaque jour par pg_cron, ou « Recalculer »). Jamais deux fois le même palier.
create table public.seniority_credits (
  employee_id uuid not null references public.profiles on delete cascade on update cascade,
  tier smallint not null,          -- 1 = 1re tranche (5 ans), 2 = 2e (10 ans)…
  years smallint not null,
  days numeric(3,1) not null,
  credited_on date not null default current_date,
  primary key (employee_id, tier)
);

create or replace function public.accrue_seniority(p_date date default current_date) returns integer
language plpgsql security definer set search_path = public as $$
declare st settings; e profiles; tiers int; k int; n int := 0;
begin
  if auth.uid() is not null and not public.is_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  for st in select * from settings where auth.uid() is null or id = public.my_company() loop
    for e in select * from profiles where company_id = st.id and active and hire_date is not null and contract_type = any(st.seniority_contracts)
                                      and role in ('employee','assistant','manager','admin') loop
      tiers := floor(extract(year from age(p_date, e.hire_date)) / st.seniority_years)::int;
      for k in 1 .. tiers loop
        if not exists (select 1 from seniority_credits where employee_id = e.id and tier = k) then
          insert into seniority_credits (employee_id, tier, years, days, credited_on) values (e.id, k, k * st.seniority_years, st.seniority_days, p_date);
          update profiles set seniority_balance = seniority_balance + st.seniority_days where id = e.id;
          if coalesce((st.notify ->> 'credit')::boolean, true) then
            perform public.notify(e.id, 'Jour d''ancienneté crédité', '+' || trim_scale(st.seniority_days) || ' j pour ' || k * st.seniority_years || ' ans d''ancienneté.');
          end if;
          n := n + 1;
        end if;
      end loop;
    end loop;
  end loop;
  return n;
end $$;

