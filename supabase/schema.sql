-- ---------- Création / liaison du profil à la création d'un compte ----------
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- fiche créée à l'avance avec le même e-mail : on la relie au compte
  if exists (select 1 from profiles where lower(email) = lower(new.email) and not has_account) then
    perform set_config('hpg.silent', '1', true);
    update profiles set id = new.id, has_account = true,
      full_name = case when full_name = '' then coalesce(new.raw_user_meta_data->>'full_name', '') else full_name end,
      role = case when exists (select 1 from settings where lower(developer_email) = lower(new.email)) then 'developer' else role end
    where lower(email) = lower(new.email) and not has_account;
    perform set_config('hpg.silent', '0', true);
    return new;
  end if;
  -- inscription libre : rattachée à l'entreprise s'il n'y en a qu'une, sinon le développeur l'attribue
  insert into profiles (id, email, full_name, role, company_id)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', ''),
          case when exists (select 1 from settings where lower(developer_email) = lower(new.email)) then 'developer' else 'pending' end,
          case when (select count(*) from companies) = 1 then (select min(id) from companies) else (select min(id) from companies where exists (select 1 from settings where lower(developer_email) = lower(new.email))) end);
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

-- Dernière connexion (affichée dans l'onglet Équipe)
create or replace function public.last_sign_ins() returns table (id uuid, last_sign_in_at timestamptz)
language sql stable security definer set search_path = public, auth as $$
  select u.id, u.last_sign_in_at from auth.users u join profiles p on p.id = u.id
  where (public.is_admin() and p.company_id = public.my_company()) or exists (select 1 from profile_services ps where ps.profile_id = p.id and public.staff_of(ps.service_id))
$$;

