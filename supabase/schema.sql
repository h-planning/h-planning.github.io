  or (employee_id = auth.uid() and (request_id is not null or public.is_published(service_id, day)))
  or (public.employee_right('team_planning') and public.in_my_services(service_id) and public.is_published(service_id, day)
      and exists (select 1 from profiles p where p.id = employee_id))
);
create policy "shifts ajout" on public.shifts for insert to authenticated with check (public.can('planning', service_id));
create policy "shifts modification" on public.shifts for update to authenticated using (public.can('planning', service_id)) with check (public.can('planning', service_id));
create policy "shifts suppression" on public.shifts for delete to authenticated using (public.can('planning', service_id));

