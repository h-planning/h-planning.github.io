-- Service du salarié + repos minimum + chevauchement (sur tous ses services)
create or replace function public.shifts_before() returns trigger
language plpgsql security definer set search_path = public as $$
declare a_s timestamp; a_e timestamp; o record; gap interval; minrest numeric;
begin
  if not public.works_in(new.employee_id, new.service_id) then
    raise exception 'Ce salarié n''appartient pas à ce service.';
  end if;
  -- nouvel horaire d'un modèle de shift appliqué aux jours à venir (Paramètres) : pas de contrôle shift par shift
  if new.kind = 'work' and current_setting('hpg.propagate', true) is distinct from '1' then
    a_s := new.day + new.start_time;
    a_e := new.day + new.end_time + case when new.end_time <= new.start_time then interval '1 day' else interval '0' end;
    select min_rest_hours into minrest from settings where id = public.svc_company(new.service_id);
    for o in
      select s.day, s.start_time, s.end_time, (s.day + s.start_time) as os,
             (s.day + s.end_time + case when s.end_time <= s.start_time then interval '1 day' else interval '0' end) as oe
      from shifts s
      where s.employee_id = new.employee_id and s.kind = 'work' and s.id <> new.id
        and s.day between new.day - 1 and new.day + 1
    loop
      if a_s < o.oe and o.os < a_e then
        raise exception 'Ce shift chevauche l''horaire du % (% – %).', to_char(o.day, 'DD/MM'), to_char(o.start_time, 'HH24"h"MI'), to_char(o.end_time, 'HH24"h"MI');
      end if;
      gap := case when a_s >= o.oe then a_s - o.oe else o.os - a_e end;
      if gap < make_interval(mins => (minrest * 60)::int) then
        raise exception 'Repos de % h non respecté : seulement % entre ce shift et celui du % (% – %).',
          trim_scale(minrest), to_char(gap, 'HH24"h"MI'), to_char(o.day, 'DD/MM'), to_char(o.start_time, 'HH24"h"MI'), to_char(o.end_time, 'HH24"h"MI');
      end if;
    end loop;
  end if;
  new.updated_at := now();
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  return new;
end $$;
create trigger shifts_before before insert or update on public.shifts
for each row execute function public.shifts_before();

-- Prévient le salarié quand un shift d'une semaine déjà publiée change
create or replace function public.shifts_notify() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record; verb text;
begin
  r := coalesce(new, old);
  if r.request_id is not null then return null; end if;
  if current_setting('hpg.silent', true) = '1' then return null; end if;
  if not public.notify_on('change') then return null; end if;
  if not public.is_published(r.service_id, r.day) then return null; end if;
  if r.employee_id = auth.uid() then return null; end if;
  verb := case tg_op when 'INSERT' then 'ajouté' when 'DELETE' then 'supprimé' else 'modifié' end;
  perform public.notify(r.employee_id, 'Planning modifié',
    'Votre planning du ' || to_char(r.day, 'DD/MM/YYYY') || ' a été ' || verb || '.');
  return null;
end $$;
create trigger shifts_notify after insert or update or delete on public.shifts
for each row execute function public.shifts_notify();

create or replace function public.publish_month(p_service smallint, p_month date) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.can('publish', p_service) then raise exception 'Vous n''avez pas le droit de publier ce service.'; end if;
  insert into published_months (service_id, month) values (p_service, public.month_of(p_month))
  on conflict do nothing;
  if public.notify_on('publish') then
    insert into notifications (user_id, title, body)
    select p.id, 'Planning publié', 'Le planning de ' || trim(to_char(public.month_of(p_month), 'TMMonth YYYY')) || ' est disponible.'
    from profiles p where p.active and p.has_account and p.role in ('employee','assistant','manager') and public.works_in(p.id, p_service);
  end if;
end $$;

create or replace function public.unpublish_month(p_service smallint, p_month date) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.can('publish', p_service) then raise exception 'Vous n''avez pas le droit de dépublier ce service.'; end if;
  delete from published_months where service_id = p_service and month = public.month_of(p_month);
end $$;

