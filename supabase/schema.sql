-- ---------- Planning ----------
-- kind : work = travail | repos | formation (comme un repos) | cp = congé payé | ferie = jour férié rendu
--        recup = jour récupéré (pris sur les jours à récupérer) | rendre = jour à rendre (le salarié devra le rendre)
--        anciennete = jour d'ancienneté | ot_day = récup heures supp | maladie | at = accident du travail
--        css = congé sans solde | absence
create table public.shifts (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.profiles on delete cascade on update cascade,
  service_id smallint not null references public.services,
  day date not null,
  kind text not null default 'work'
    check (kind in ('work','repos','formation','cp','ferie','recup','rendre','anciennete','ot_day','maladie','at','css','absence')),
  template_id smallint references public.shift_templates on delete set null,
  start_time time,
  end_time time,
  break_min smallint,            -- null = automatique (paramètres)
  color text check (color in ('open','am','mid','sky','pm','night')),
  label text,
  note text,
  extra_pay boolean not null default false,   -- « Extra à payer »
  jour_rendu boolean not null default false,  -- ce shift rend un jour dû par le salarié (owed_id = le jour rendu)
  jour_sup boolean not null default false,    -- shift supplémentaire : +1 jour à récupérer
  owed_id uuid,                               -- jour de la liste soldé par ce shift (JF, JR ou « Jour rendu »)
  request_id uuid,
  updated_by uuid default auth.uid(),
  updated_at timestamptz not null default now(),
  check (kind <> 'work' or (start_time is not null and end_time is not null)),
  check (not (jour_rendu and jour_sup))
);
create index on public.shifts (employee_id, day);
create index on public.shifts (service_id, day);

