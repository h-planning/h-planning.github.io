-- Modification d'un modèle de shift dans les Paramètres : le nouvel horaire s'applique partout,
-- à tous les shifts de ce modèle à partir d'aujourd'hui (planning, fiches, pointage, exports, pour tous les utilisateurs).
-- Les jours passés gardent l'horaire réellement travaillé. Chaque salarié concerné reçoit une seule notification.
create or replace function public.templates_propagate() returns trigger
language plpgsql security definer set search_path = public as $$
declare d0 date := (now() at time zone 'Europe/Paris')::date; e uuid;
begin
  if (new.start_time, new.end_time) is not distinct from (old.start_time, old.end_time) then return null; end if;
  perform set_config('hpg.propagate', '1', true);
  perform set_config('hpg.silent', '1', true);
  create temporary table if not exists _tpl_emp (employee_id uuid) on commit drop;
  delete from _tpl_emp;
  with u as (
    update shifts set start_time = new.start_time, end_time = new.end_time, template_id = new.id
    where kind = 'work' and day >= d0
      and (template_id = new.id
           or (template_id is null and start_time = old.start_time and end_time = old.end_time
               and (case when old.service_id is null then public.svc_company(service_id) = new.company_id else service_id = old.service_id end)))
    returning employee_id, service_id, day)
  insert into _tpl_emp select distinct employee_id from u where public.is_published(service_id, day);
  perform set_config('hpg.propagate', '', true);
  perform set_config('hpg.silent', '', true);
  if public.notify_on('change') then
    for e in select distinct employee_id from _tpl_emp loop
      perform public.notify(e, 'Horaire modifié', 'Le shift « ' || new.name || ' » passe à ' || to_char(new.start_time, 'HH24"h"MI') || ' – ' || to_char(new.end_time, 'HH24"h"MI') || ' à partir d''aujourd''hui.');
    end loop;
  end if;
  return null;
end $$;
create trigger templates_propagate after update on public.shift_templates
for each row execute function public.templates_propagate();

