create or replace function public.overtime_before() returns trigger
language plpgsql security definer set search_path = public as $$
declare sh shifts;
begin
  select * into sh from shifts where id = new.shift_id;
  if sh.id is null then raise exception 'Shift introuvable.'; end if;
  if sh.kind <> 'work' then raise exception 'Les heures supp ne peuvent être inscrites que sur un shift travaillé.'; end if;
  if auth.uid() is not null and not public.can('overtime', sh.service_id) then raise exception 'Vous n''avez pas le droit d''inscrire des heures supp.'; end if;
  new.employee_id := sh.employee_id; new.service_id := sh.service_id; new.day := sh.day;
  new.created_by := coalesce(auth.uid(), new.created_by);
  return new;
end $$;
