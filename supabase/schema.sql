create policy "jours dus lecture" on public.owed_days for select to authenticated using (
  employee_id = auth.uid()
  or exists (select 1 from profile_services ps where ps.profile_id = owed_days.employee_id and public.staff_of(ps.service_id)));
create policy "jours dus ajout" on public.owed_days for insert to authenticated with check (
  exists (select 1 from profile_services ps where ps.profile_id = employee_id and public.can('owed', ps.service_id)));
create policy "jours dus suppression" on public.owed_days for delete to authenticated using (
  rendered_shift_id is null and source_shift_id is null
  and exists (select 1 from profile_services ps where ps.profile_id = owed_days.employee_id and public.can('owed', ps.service_id)));

