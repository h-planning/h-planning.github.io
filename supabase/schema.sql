create or replace function public.shifts_sync_overtime() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind <> 'work' then delete from overtime_entries where shift_id = new.id;
  elsif (new.day, new.employee_id, new.service_id) is distinct from (old.day, old.employee_id, old.service_id) then
    update overtime_entries set day = new.day, employee_id = new.employee_id, service_id = new.service_id where shift_id = new.id;
  end if;
  return null;
end $$;
create trigger shifts_sync_overtime after update on public.shifts
for each row execute function public.shifts_sync_overtime();

-- Solde d'heures supp (minutes) = inscrites + correction − récupérations × durée d'une récup
create or replace function public.ot_balance(p_emp uuid) returns integer
language sql stable security definer set search_path = public as $$
  select coalesce((select sum(minutes) from overtime_entries where employee_id = p_emp), 0)::int
       + coalesce((select recup_adjust_min from profiles where id = p_emp), 0)
       - (select count(*) from shifts where employee_id = p_emp and kind = 'ot_day')::int * (select ot_day_minutes from settings where id = public.emp_company(p_emp))
$$;

-- ---------- Liste des jours dus, par salarié ----------
-- type ferie  : jour férié dû au salarié (crédité par le manager / l'administrateur à la date choisie par l'entreprise)
-- type recup  : jour à récupérer, dû au salarié (ajouté à la main, ou par un shift coché « Jour supplémentaire à récupérer »)
-- type rendre : jour à rendre, dû par le salarié (créé quand on pose « Jour à rendre » dans le planning)
-- Une ligne est soldée (rendered_shift_id) par : un « Jour férié » (ferie), un « Jour récupéré » (recup),
-- ou un shift travaillé coché « Jour rendu » (rendre). Retirer ce shift la rouvre.
create table public.owed_days (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.profiles on delete cascade on update cascade,
  service_id smallint references public.services,
  type text not null check (type in ('ferie','recup','rendre')),
  origin_date date,
  days numeric(3,1) not null default 1 check (days in (0.5, 1)),
  reason text,
  source_shift_id uuid references public.shifts on delete cascade,  -- jour posé à l'origine de la ligne
  rendered_shift_id uuid references public.shifts on delete set null,
  rendered_on date,
  rendered_note text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index on public.owed_days (employee_id, type) where rendered_shift_id is null;
alter table public.shifts add constraint shifts_owed_fk foreign key (owed_id) references public.owed_days on delete set null;

create or replace function public.owed_refresh(p_emp uuid) returns void
language sql security definer set search_path = public as $$
  update profiles set
    ferie_balance = coalesce((select sum(days) from owed_days where employee_id = p_emp and type = 'ferie'  and rendered_shift_id is null), 0),
    recup_days    = coalesce((select sum(days) from owed_days where employee_id = p_emp and type = 'recup'  and rendered_shift_id is null), 0),
    rendre_days   = coalesce((select sum(days) from owed_days where employee_id = p_emp and type = 'rendre' and rendered_shift_id is null), 0)
  where id = p_emp
$$;

create or replace function public.owed_before() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    select service_id into new.service_id from profiles where id = new.employee_id;
    if auth.uid() is not null and new.source_shift_id is null
       and not exists (select 1 from profile_services ps where ps.profile_id = new.employee_id and public.can('owed', ps.service_id)) then
      raise exception 'Vous ne gérez pas les jours dus de ce salarié.';
    end if;
    new.created_by := coalesce(auth.uid(), new.created_by);
  end if;
  if new.rendered_shift_id is null then new.rendered_on := null; new.rendered_note := null; end if;
  return new;
end $$;
create trigger owed_before before insert or update on public.owed_days for each row execute function public.owed_before();

create or replace function public.owed_after() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform public.owed_refresh(coalesce(new.employee_id, old.employee_id));
  return null;
end $$;
create trigger owed_after after insert or update or delete on public.owed_days for each row execute function public.owed_after();

create or replace function public.credit_ferie(p_ids uuid[], p_days numeric, p_holiday date, p_reason text) returns integer
language plpgsql security definer set search_path = public as $$
declare e profiles; n integer := 0; k numeric;
begin
  if coalesce(p_days, 0) <= 0 or p_days > 5 or (p_days * 2) <> floor(p_days * 2) then raise exception 'Indiquez un nombre de jours entre 0,5 et 5 (par demi-journée).'; end if;
  for e in select * from profiles where id = any(p_ids) loop
    if not exists (select 1 from profile_services ps where ps.profile_id = e.id and public.can('owed', ps.service_id)) then
      raise exception 'Vous ne gérez pas les jours de %.', e.full_name;
    end if;
    k := p_days;
    while k > 0 loop
      insert into owed_days (employee_id, type, origin_date, days, reason) values (e.id, 'ferie', p_holiday, least(k, 1), p_reason);
      k := k - least(k, 1);
    end loop;
    if public.notify_on('credit') then
      perform public.notify(e.id, 'Jour férié crédité', '+' || trim_scale(p_days) || ' j' || coalesce(' (férié du ' || to_char(p_holiday, 'DD/MM/YYYY') || ')', '') || '.');
    end if;
    n := n + 1;
  end loop;
  return n;
end $$;

-- ---------- Compteurs reliés au planning ----------
-- Poser un élément applique son effet ; le supprimer l'annule ; le remplacer annule l'ancien puis applique le nouveau.
create or replace function public.shifts_balances_before() returns trigger
language plpgsql security definer set search_path = public as $$
declare o owed_days; bal numeric; same boolean;
begin
  if tg_op = 'UPDATE' and current_setting('hpg.propagate', true) = '1' then return new; end if; -- seul l'horaire change
  if tg_op = 'DELETE' then
    -- un jour posé dont la ligne a déjà été soldée ne peut pas être retiré
    select * into o from owed_days where source_shift_id = old.id and rendered_shift_id is not null and rendered_shift_id <> old.id limit 1;
    if o.id is not null then
      raise exception '% du % a déjà été % le % : retirez d''abord ce jour-là.',
        case o.type when 'rendre' then 'Le jour à rendre' else 'Le jour à récupérer' end, to_char(o.origin_date, 'DD/MM'),
        case o.type when 'rendre' then 'rendu' else 'récupéré' end, to_char(o.rendered_on, 'DD/MM/YYYY');
    end if;
    return old;
  end if;

  -- nettoyage selon le type
  if new.kind <> 'work' then
    new.extra_pay := false; new.jour_rendu := false; new.jour_sup := false;
    new.start_time := null; new.end_time := null; new.break_min := null; new.template_id := null;
  end if;
  if not (new.kind in ('ferie','recup') or (new.kind = 'work' and new.jour_rendu)) then new.owed_id := null; end if;
  if new.extra_pay and new.jour_sup then
    raise exception 'Cochez « Extra à payer » ou « Jour supplémentaire à récupérer », pas les deux.';
  end if;

  -- retirer l'origine d'une ligne déjà soldée (jour à rendre, jour sup) est refusé
  if tg_op = 'UPDATE' and ((old.kind = 'rendre' and new.kind <> 'rendre') or (old.jour_sup and not new.jour_sup)
                           or new.employee_id <> old.employee_id) then
    select * into o from owed_days where source_shift_id = old.id and rendered_shift_id is not null limit 1;
    if o.id is not null then
      raise exception '% du % a déjà été % le % : retirez d''abord ce jour-là.',
        case o.type when 'rendre' then 'Le jour à rendre' else 'Le jour à récupérer' end, to_char(o.origin_date, 'DD/MM'),
        case o.type when 'rendre' then 'rendu' else 'récupéré' end, to_char(o.rendered_on, 'DD/MM/YYYY');
    end if;
  end if;

  -- jour férié / jour récupéré : une ligne de la liste (choisie, sinon la plus ancienne)
  if new.kind in ('ferie','recup') then
    if new.owed_id is not null then
      select * into o from owed_days where id = new.owed_id;
      if o.id is null or o.employee_id <> new.employee_id or o.type <> new.kind then raise exception 'Ce jour ne correspond pas à ce salarié.'; end if;
      if o.rendered_shift_id is not null and o.rendered_shift_id <> new.id then raise exception 'Ce jour a déjà été pris le %.', to_char(o.rendered_on, 'DD/MM/YYYY'); end if;
    else
      select * into o from owed_days where employee_id = new.employee_id and type = new.kind and (rendered_shift_id is null or rendered_shift_id = new.id)
       order by (rendered_shift_id = new.id) desc nulls last, origin_date nulls last, created_at limit 1;
      if o.id is null then
        raise exception '% n''a aucun %.', (select full_name from profiles where id = new.employee_id),
          case new.kind when 'ferie' then 'jour férié dû' else 'jour à récupérer' end;
      end if;
      new.owed_id := o.id;
    end if;
  end if;

  -- shift « Jour rendu » : choix obligatoire d'un jour à rendre
  if new.kind = 'work' and new.jour_rendu then
    if new.owed_id is null then raise exception 'Choisissez dans la liste le jour à rendre qui est rendu.'; end if;
    select * into o from owed_days where id = new.owed_id;
    if o.id is null or o.employee_id <> new.employee_id or o.type <> 'rendre' then raise exception 'Ce jour à rendre ne correspond pas à ce salarié.'; end if;
    if o.rendered_shift_id is not null and o.rendered_shift_id <> new.id then raise exception 'Ce jour a déjà été rendu le %.', to_char(o.rendered_on, 'DD/MM/YYYY'); end if;
  end if;

  -- shift « Jour supplémentaire à récupérer » : seulement sans jour à rendre en cours
  if new.kind = 'work' and new.jour_sup and (tg_op = 'INSERT' or not old.jour_sup) then
    select coalesce(sum(days), 0) into bal from owed_days where employee_id = new.employee_id and type = 'rendre' and rendered_shift_id is null;
    if bal > 0 then
      raise exception 'Ce salarié a encore % jour(s) à rendre : cochez « Jour rendu » au lieu de « Jour supplémentaire à récupérer ».', trim_scale(bal);
    end if;
  end if;

  -- congé payé : solde suffisant (1 jour par jour ouvrable)
  same := tg_op = 'UPDATE' and old.employee_id = new.employee_id and old.kind = new.kind and old.day = new.day;
  if new.kind = 'cp' and new.request_id is null and public.is_ouvrable(new.day) and not same then
    select cp_balance into bal from profiles where id = new.employee_id;
    if tg_op = 'UPDATE' and old.kind = 'cp' and old.employee_id = new.employee_id and public.is_ouvrable(old.day) then bal := bal + 1; end if;
    if bal < 1 then raise exception 'Solde de congés payés insuffisant (% j).', trim_scale(bal); end if;
  end if;
  -- jour d'ancienneté
  if new.kind = 'anciennete' and new.request_id is null and not same then
    select seniority_balance into bal from profiles where id = new.employee_id;
    if tg_op = 'UPDATE' and old.kind = 'anciennete' and old.employee_id = new.employee_id then bal := bal + 1; end if;
    if bal < 1 then raise exception 'Solde de jours d''ancienneté insuffisant (% j).', trim_scale(bal); end if;
  end if;
  return new;
end $$;
create trigger shifts_balances_before before insert or update or delete on public.shifts
for each row execute function public.shifts_balances_before();

create or replace function public.shifts_balances_after() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' and current_setting('hpg.propagate', true) = '1' then return null; end if;
  -- annuler l'effet de l'ancien élément
  if tg_op in ('UPDATE','DELETE') then
    if old.kind = 'cp' and public.is_ouvrable(old.day) then
      update profiles set cp_balance = cp_balance + 1 where id = old.employee_id;
    end if;
    if old.kind = 'anciennete' then
      update profiles set seniority_balance = seniority_balance + 1 where id = old.employee_id;
    end if;
    if old.owed_id is not null and (tg_op = 'DELETE' or new.owed_id is distinct from old.owed_id) then
      update owed_days set rendered_shift_id = null where id = old.owed_id and rendered_shift_id = old.id;
    end if;
    if tg_op = 'UPDATE' then
      if (old.kind = 'rendre' and new.kind <> 'rendre') or (old.jour_sup and not new.jour_sup) or new.employee_id <> old.employee_id then
        delete from owed_days where source_shift_id = old.id;
      end if;
    end if;
    -- (DELETE : les lignes créées par ce jour disparaissent avec lui — clé étrangère en cascade)
  end if;
  -- appliquer l'effet du nouvel élément
  if tg_op in ('INSERT','UPDATE') then
    if new.kind = 'cp' and public.is_ouvrable(new.day) then
      update profiles set cp_balance = cp_balance - 1 where id = new.employee_id;
    end if;
    if new.kind = 'anciennete' then
      update profiles set seniority_balance = seniority_balance - 1 where id = new.employee_id;
    end if;
    if new.owed_id is not null then
      update owed_days set rendered_shift_id = new.id, rendered_on = new.day, rendered_note = new.note where id = new.owed_id;
    end if;
    if new.kind = 'rendre' then
      if exists (select 1 from owed_days where source_shift_id = new.id) then
        update owed_days set origin_date = new.day, reason = coalesce(new.note, reason) where source_shift_id = new.id;
      else
        insert into owed_days (employee_id, type, origin_date, days, reason, source_shift_id) values (new.employee_id, 'rendre', new.day, 1, new.note, new.id);
      end if;
    end if;
    if new.kind = 'work' and new.jour_sup then
      if exists (select 1 from owed_days where source_shift_id = new.id) then
        update owed_days set origin_date = new.day where source_shift_id = new.id;
      else
        insert into owed_days (employee_id, type, origin_date, days, reason, source_shift_id) values (new.employee_id, 'recup', new.day, 1, 'Jour supplémentaire travaillé', new.id);
      end if;
    end if;
  end if;
  -- les compteurs de jours dus d'un salarié dont le jour a été supprimé (cascade) sont recalculés
  if tg_op = 'DELETE' then perform public.owed_refresh(old.employee_id); end if;
  return null;
end $$;
-- ---------- Congés payés en jours ouvrables ----------
-- Jour de repos décompté en CP : le 1er des jours de repos habituels du salarié (samedi pour un repos samedi-dimanche ;
-- jamais le dimanche) ; repos non renseignés = samedi. Seulement s'il a au moins 2 jours de repos.
create or replace function public.cp_rest_day(p_emp uuid) returns smallint
language sql stable security definer set search_path = public as $$
  select case
    when coalesce(cardinality(r), 0) = 0 then 6::smallint
    when cardinality(r) < 2 then null
    else coalesce((select x from unnest(r) x where x <> 7 and not ((case when x = 1 then 7 else x - 1 end)::smallint = any(r)) order by x limit 1),
                  (select min(x) from unnest(r) x where x <> 7))
  end
  from (select weekly_rest r from profiles where id = p_emp) q
$$;

-- CP posé le jour J (à la main ou par une demande) et J+1 = ce jour de repos : J+1 devient CP (repos remplacé, case vide remplie).
-- CP retiré le jour J : le CP ajouté automatiquement à J+1 redevient repos.
create or replace function public.shifts_cp_rest() returns trigger
language plpgsql security definer set search_path = public as $$
declare d date; rd smallint;
begin
  if current_setting('hpg.cprest', true) = '1' or current_setting('hpg.propagate', true) = '1' then return null; end if;
  perform set_config('hpg.cprest', '1', true);
  if tg_op in ('UPDATE','DELETE') and old.kind = 'cp' and (tg_op = 'DELETE' or new.kind <> 'cp' or new.day <> old.day) then
    d := old.day + 1;
    if exists (select 1 from shifts where employee_id = old.employee_id and day = d and kind = 'cp' and note = 'CP décompté (repos)') then
      delete from shifts where employee_id = old.employee_id and day = d and kind = 'cp' and note = 'CP décompté (repos)';
      insert into shifts (employee_id, service_id, day, kind, note) values (old.employee_id, old.service_id, d, 'repos', 'Repos hebdomadaire');
    end if;
  end if;
  if tg_op in ('INSERT','UPDATE') and new.kind = 'cp' and new.request_id is null then   -- une demande de CP inclut déjà ce jour
    d := new.day + 1; rd := public.cp_rest_day(new.employee_id);
    if rd is not null and extract(isodow from d)::smallint = rd and public.is_ouvrable(d)
       and not exists (select 1 from shifts where employee_id = new.employee_id and day = d and kind <> 'repos') then
      delete from shifts where employee_id = new.employee_id and day = d and kind = 'repos';
      insert into shifts (employee_id, service_id, day, kind, note, request_id) values (new.employee_id, new.service_id, d, 'cp', 'CP décompté (repos)', new.request_id);
    end if;
  end if;
  perform set_config('hpg.cprest', '', true);
  return null;
end $$;
create trigger shifts_cp_rest after insert or update or delete on public.shifts
for each row execute function public.shifts_cp_rest();

