-- ---------- Repos hebdomadaire posé automatiquement ----------
-- Pose « Repos » sur les jours de repos habituels du salarié (1 = lundi … 7 = dimanche) entre deux dates,
-- seulement sur les jours encore vides ; retire les repos posés automatiquement qui ne tombent plus sur un jour de repos.
create or replace function public.apply_weekly_rest(p_emp uuid, p_from date, p_to date) returns integer
language plpgsql security definer set search_path = public as $$
declare e profiles; svc smallint; d date; n integer := 0;
begin
  select * into e from profiles where id = p_emp;
  if e.id is null then raise exception 'Salarié introuvable.'; end if;
  svc := coalesce(e.service_id, (select min(service_id) from profile_services where profile_id = e.id));
  if svc is null or not public.can('planning', svc) then raise exception 'Vous n''avez pas le droit de modifier le planning de ce salarié.'; end if;
  p_from := greatest(p_from, coalesce(e.hire_date, p_from));
  if p_to > p_from + 400 then p_to := p_from + 400; end if;
  perform set_config('hpg.silent', '1', true);
  delete from shifts where employee_id = e.id and kind = 'repos' and note = 'Repos hebdomadaire' and day between p_from and p_to
    and not (extract(isodow from day)::smallint = any(e.weekly_rest));
  for d in select g::date from generate_series(p_from, p_to, interval '1 day') g loop
    if extract(isodow from d)::smallint = any(e.weekly_rest) and not exists (select 1 from shifts where employee_id = e.id and day = d) then
      insert into shifts (employee_id, service_id, day, kind, note) values (e.id, svc, d, 'repos', 'Repos hebdomadaire');
      n := n + 1;
    end if;
  end loop;
  perform set_config('hpg.silent', '', true);
  return n;
end $$;

-- ---------- Entreprises : création, fiche, choix de l'entreprise ouverte ----------
-- Le développeur passe d'une entreprise à l'autre : tout l'application (planning, équipe, paramètres, exports) suit.
create or replace function public.set_my_company(p_company smallint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_dev() then raise exception 'Réservé au développeur.'; end if;
  if not exists (select 1 from companies where id = p_company) then raise exception 'Entreprise introuvable.'; end if;
  update profiles set company_id = p_company, service_id = null where id = auth.uid();
  delete from profile_services where profile_id = auth.uid();
