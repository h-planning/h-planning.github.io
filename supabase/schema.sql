create or replace function public.audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare r jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  insert into audit_log (table_name, row_id, action, old_data, new_data, company_id)
  values (tg_table_name, r ->> 'id', tg_op,
          case when tg_op <> 'INSERT' then to_jsonb(old) end,
          case when tg_op <> 'DELETE' then to_jsonb(new) end,
          coalesce(case when tg_table_name in ('settings','companies') then (r ->> 'id')::smallint end,
                   (r ->> 'company_id')::smallint,
                   public.svc_company((r ->> 'service_id')::smallint),
                   public.emp_company((r ->> 'employee_id')::uuid),
                   public.my_company()));
  return null;
end $$;
