-- p : champs de la fiche entreprise ; à la création (développeur) :
--   copy_from = n° d'une entreprise dont on recopie les paramètres, les services, les barèmes et les shifts
--   services  = liste de noms de services à créer (si pas de copie)
create or replace function public.save_company(p jsonb) returns companies
language plpgsql security definer set search_path = public as $$
declare c companies; src smallint := nullif(p->>'copy_from', '')::smallint; sv record; nid smallint; nm text;
begin
  if p ? 'id' and nullif(p->>'id', '') is not null then
    select * into c from companies where id = (p->>'id')::smallint for update;
    if c.id is null then raise exception 'Entreprise introuvable.'; end if;
    if not (public.is_dev() or (public.is_admin() and c.id = public.my_company() and public.admin_right('company'))) then raise exception 'Accès refusé.'; end if;
  else
    if not public.is_dev() then raise exception 'Seul le développeur peut créer une entreprise.'; end if;
  end if;
  nm := coalesce(nullif(trim(p->>'name'), ''), c.name);
  if nm is null then raise exception 'Indiquez le nom de l''entreprise.'; end if;
  if c.id is null then
    perform set_config('hpg.keep_company', '1', true);
    insert into companies (name, features) values (nm, coalesce((select features from companies where id = src), '{}')) returning * into c;
    if src is not null and exists (select 1 from settings where id = src) then
      insert into settings select (jsonb_populate_record(null::settings, to_jsonb(st) || jsonb_build_object(
        'id', c.id, 'hotel_name', nm, 'company_name', coalesce(nullif(p->>'legal_name', ''), nm),
        'presence_hotel_label', upper(nm), 'pointage_title', upper(nm), 'updated_at', now(), 'updated_by', auth.uid()))).*
      from settings st where st.id = src;
      for sv in select * from services where company_id = src and not archived order by sort loop
        insert into services (company_id, name, locations, sort, staffing) values (c.id, sv.name, sv.locations, sv.sort, sv.staffing) returning id into nid;
        insert into shift_templates (company_id, service_id, name, start_time, end_time, color, sort, active, rooms, label, bg, fg)
        select c.id, nid, name, start_time, end_time, color, sort, active, rooms, label, bg, fg from shift_templates where service_id = sv.id;
      end loop;
      insert into shift_templates (company_id, service_id, name, start_time, end_time, color, sort, active, rooms, label, bg, fg)
      select c.id, null, name, start_time, end_time, color, sort, active, rooms, label, bg, fg from shift_templates where company_id = src and service_id is null;
    else
      insert into settings (id, hotel_name, company_name, presence_hotel_label, pointage_title, developer_email)
      values (c.id, nm, coalesce(nullif(p->>'legal_name', ''), nm), upper(nm), upper(nm),
              coalesce((select developer_email from settings order by id limit 1), 'paulr.rochester@gmail.com'));
      insert into services (company_id, name, sort)
      select c.id, trim(x), row_number() over () from jsonb_array_elements_text(coalesce(p->'services', '[]')) x where trim(x) <> '';
    end if;
    perform set_config('hpg.keep_company', '', true);
  end if;
  update companies set
    name = nm,
    legal_name = case when p ? 'legal_name' then nullif(trim(p->>'legal_name'), '') else legal_name end,
    siret = case when p ? 'siret' then nullif(trim(p->>'siret'), '') else siret end,
    ape_code = case when p ? 'ape_code' then nullif(trim(p->>'ape_code'), '') else ape_code end,
    vat_number = case when p ? 'vat_number' then nullif(trim(p->>'vat_number'), '') else vat_number end,
    address = case when p ? 'address' then nullif(trim(p->>'address'), '') else address end,
    postal_code = case when p ? 'postal_code' then nullif(trim(p->>'postal_code'), '') else postal_code end,
    city = case when p ? 'city' then nullif(trim(p->>'city'), '') else city end,
    country = coalesce(nullif(trim(p->>'country'), ''), country),
    phone = case when p ? 'phone' then nullif(trim(p->>'phone'), '') else phone end,
    email = case when p ? 'email' then nullif(lower(trim(p->>'email')), '') else email end,
    website = case when p ? 'website' then nullif(trim(p->>'website'), '') else website end,
    director = case when p ? 'director' then nullif(trim(p->>'director'), '') else director end,
    contact_name = case when p ? 'contact_name' then nullif(trim(p->>'contact_name'), '') else contact_name end,
    contact_email = case when p ? 'contact_email' then nullif(lower(trim(p->>'contact_email')), '') else contact_email end,
    collective_agreement = case when p ? 'collective_agreement' then nullif(trim(p->>'collective_agreement'), '') else collective_agreement end,
    category = case when p ? 'category' then nullif(trim(p->>'category'), '') else category end,
    rooms = case when p ? 'rooms' then nullif(p->>'rooms', '')::smallint else rooms end,
    notes = case when p ? 'notes' then nullif(trim(p->>'notes'), '') else notes end,
    active = case when p ? 'active' and public.is_dev() then (p->>'active')::boolean else active end,
    features = case when public.is_dev() and jsonb_typeof(p->'features') = 'object' then p->'features' else features end
  where id = c.id returning * into c;
  -- le nom affiché dans l'application et sur les impressions suit la fiche
  update settings set hotel_name = c.name, company_name = coalesce(c.legal_name, company_name) where id = c.id;
  return c;
end $$;

