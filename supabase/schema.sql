-- ---------- Profils (un par salarié ; relié à un compte de connexion quand il en a un) ----------
-- role : pending | employee | assistant | manager | admin | developer
--   developer : compte technique, tous les droits, invisible dans les effectifs
create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  email text,
  company_id smallint default 1 references public.companies on delete cascade,  -- entreprise (développeur : celle qu'il a ouverte)
  has_account boolean not null default true,
  full_name text not null default '',
  role text not null default 'pending' check (role in ('pending','employee','assistant','manager','admin','developer')),
  service_id smallint references public.services,  -- service principal (les autres dans profile_services)
  location text,                                   -- localisation dans le service (BACKOFFICE, RECEP NUIT…)
  job_title text,                                  -- poste / fonction (fiche de présence : case « Code »)
  weekly_rest smallint[] not null default '{}',    -- jours de repos habituels (1 = lundi … 7 = dimanche)
  contract_type text not null default 'cdi',
  contract_hours numeric(4,1) not null default 39,
  hire_date date,                                  -- date d'entrée : base des CP et de l'ancienneté
  cp_balance numeric(5,1) not null default 0,
  ferie_balance numeric(5,1) not null default 0,   -- jours fériés dus (tenu à jour depuis owed_days)
  recup_days numeric(5,1) not null default 0,      -- jours à récupérer, dus au salarié (owed_days)
  rendre_days numeric(5,1) not null default 0,     -- jours à rendre, dus par le salarié (owed_days)
  seniority_balance numeric(5,1) not null default 0,
  recup_adjust_min integer not null default 0,     -- correction manuelle du compteur d'heures supp (minutes)
  active boolean not null default true,
  must_change_pw boolean not null default false,   -- code provisoire remis par l'encadrement : nouveau mot de passe à choisir à la 1re connexion
  created_at timestamptz not null default now()
);
create unique index profiles_email_unique on public.profiles (lower(email)) where email is not null;

create table public.profile_services (
  profile_id uuid not null references public.profiles on delete cascade on update cascade,
  service_id smallint not null references public.services,
  primary key (profile_id, service_id)
);

-- le service principal fait toujours partie de la liste
create or replace function public.profiles_sync_services() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.service_id is not null then
    insert into profile_services values (new.id, new.service_id) on conflict do nothing;
  end if;
  return null;
end $$;
create trigger profiles_sync_services after insert or update of service_id on public.profiles
for each row execute function public.profiles_sync_services();

-- ---------- Fonctions d'aide aux droits (security definer = pas de boucle RLS) ----------
create or replace function public.mfa_ok() returns boolean
language sql stable security definer set search_path = public as $$
  select not coalesce((select require_email_code from settings where id = (select company_id from profiles where id = auth.uid())), false)
      or exists (select 1 from jsonb_array_elements(coalesce(auth.jwt() -> 'amr', '[]'::jsonb)) a where a ->> 'method' <> 'password')
$$;

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as
$$ select role from profiles where id = auth.uid() and active and public.mfa_ok() $$;

create or replace function public.is_admin() returns boolean     -- administrateur ou développeur
language sql stable security definer set search_path = public as
$$ select coalesce(public.my_role() in ('admin','developer'), false) $$;

create or replace function public.is_dev() returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce(public.my_role() = 'developer', false) $$;

-- Entreprise de la personne connectée (pour le développeur : l'entreprise ouverte)
create or replace function public.my_company() returns smallint
language sql stable security definer set search_path = public as
$$ select company_id from profiles where id = auth.uid() $$;

-- la personne a choisi son propre mot de passe (après un code provisoire)
create or replace function public.pw_changed() returns void
language sql security definer set search_path = public as
$$ update profiles set must_change_pw = false where id = auth.uid() $$;

create or replace function public.svc_company(svc smallint) returns smallint
language sql stable security definer set search_path = public as
$$ select company_id from services where id = svc $$;

create or replace function public.emp_company(p_emp uuid) returns smallint
language sql stable security definer set search_path = public as
$$ select company_id from profiles where id = p_emp $$;

create or replace function public.in_my_company(svc smallint) returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce(public.svc_company(svc) = public.my_company(), false) $$;

-- Droits de l'administrateur : réglés uniquement par le développeur (Paramètres → Droits des rôles) ; tous accordés par défaut
create or replace function public.admin_right(r text) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_dev() or (public.my_role() = 'admin'
    and coalesce(((select rights from settings where id = public.my_company()) -> 'admin' ->> r)::boolean, true))
$$;

create or replace function public.my_services() returns smallint[]
language sql stable security definer set search_path = public as
$$ select coalesce(array_agg(service_id), '{}') from profile_services where profile_id = auth.uid() $$;

create or replace function public.in_my_services(svc smallint) returns boolean
language sql stable security definer set search_path = public as
$$ select svc = any(public.my_services()) $$;

-- Droit « r » sur le service « svc » (toujours un service de son entreprise) : admin / développeur toujours ;
-- manager et assistant selon les Paramètres de l'entreprise
create or replace function public.can(r text, svc smallint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.in_my_company(svc) and (
    public.is_dev()
    or (public.my_role() = 'admin' and coalesce(((select rights from settings where id = public.svc_company(svc)) -> 'admin' ->> r)::boolean, true))
    or (public.my_role() in ('manager','assistant') and public.in_my_services(svc)
        and coalesce(((select rights from settings where id = public.svc_company(svc)) -> public.my_role() ->> r)::boolean, false))),
  false)
$$;

-- Le personnel d'encadrement (manager, assistant) voit toujours le planning de ses services
create or replace function public.staff_of(svc smallint) returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce(public.in_my_company(svc) and (public.is_admin() or (public.my_role() in ('manager','assistant') and public.in_my_services(svc))), false) $$;

create or replace function public.employee_right(r text) returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce(((select rights from settings where id = public.my_company()) -> 'employee' ->> r)::boolean, false) $$;

create or replace function public.works_in(p_emp uuid, svc smallint) returns boolean
language sql stable security definer set search_path = public as
$$ select exists (select 1 from profile_services where profile_id = p_emp and service_id = svc) $$;

